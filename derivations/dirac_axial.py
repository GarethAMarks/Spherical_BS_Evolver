"""
Linearised AXIAL-parity (parity (-1)^(L+1)), axisymmetric (M = 0) perturbations of free spherical Dirac stars, using the
machinery of dirac_nonradial.py (same background, tetrad, conventions; signature (-,+,+,+), G = 1).

Why this sector, and why M = 0 suffices. The free two-spinor system is invariant under a rotation combined with a U(2)
flavour rotation of the doublet (psi_+, psi_-) (both spinors have the same mass and there is no self-interaction), and the
background is invariant under the combined rotations. The linearised operator therefore commutes with them, so its modes
form (2L + 1)-plets labelled by total (L, M) and parity: a non-axisymmetric (M != 0) mode is a rotation of an M = 0 mode
with the same L, parity and eigenvalue. The polar sector (parity (-1)^L) is in dirac_nonradial.py; this script covers the
other parity.

Ansatz. sigma.n maps the polar channels kappa = -(L+1), L onto kappa = L+1, -L (the same j' = L +- 1/2, opposite parity),
so the axial perturbation of the + spinor is the polar one with upper and lower roles exchanged:
    dpsi_+ = e^{-i w t} ( (sigma.n)(c1 Y chi_up + c2 e^{i phi} Y' chi_dn),  i (d1 Y chi_up + d2 e^{i phi} Y' chi_dn) ),
and the - spinor follows from the R_x(pi) x flavour symmetry with a sign s2 on the spin-flip parts, fixed by requiring that
the stress tensor has no polar components. Metric (Regge-Wheeler, axial, M = 0):
    h_tphi = h0 sin(theta) Y',  h_rphi = h1 sin(theta) Y'   (h0 = h1 = 0 for the other components).
Projections at generic points (Y -> y0, Y' -> y1, Y'' = -cot Y' - Lam Y):
    Dirac (+ spinor):  (sigma.n) upper = A1 Y chi_up + A2 e^{i phi} Y' chi_dn,  lower = C1 Y chi_up + C2 e^{i phi} Y' chi_dn
    Einstein:  E_tphi = Etph sin Y',  E_rphi = Erph sin Y',  E_thphi = Ethph sin (Y'' - cot Y')
    (at L = 1, Y'' - cot Y' = 0 and Ethph is absent).
Checks: background; closure at two points; the polar Einstein components vanish; the - spinor's residual is the symmetry
image of the + one. Output: relaxation/dirac_axial_coeffs.py, fields cR1 cI1 cR2 cI2 dR1 dI1 dR2 dI2 h0 h1.
Run: python3 derivations/dirac_axial.py
"""
import os, sys
import sympy as sp
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dirac_nonradial as dn
from dirac_nonradial import (sp, I, t, r, th, ph, w, mu, Lam, Y, Yp, s_, c_, up, dn as _unused, sig_n, ph_t, spinor, al, X,
                             linearised, simp, y0, y1, log, PTS, Fn)

AMAT = ['cR1', 'cI1', 'cR2', 'cI2', 'dR1', 'dI1', 'dR2', 'dI2']
AMET = ['h0', 'h1']
for n in AMAT:
    dn.fld[n] = Fn(n)
F = dn.fld
c1 = F['cR1'] + I * F['cI1']; c2 = F['cR2'] + I * F['cI2']
d1 = F['dR1'] + I * F['dI1']; d2 = F['dR2'] + I * F['dI2']
down = sp.Matrix([0, 1])

def dpsi_axial(s2):
    Up = c1 * Y * up + c2 * sp.exp(I * ph) * Yp * down
    Lp = d1 * Y * up + d2 * sp.exp(I * ph) * Yp * down
    Um = c1 * Y * down + s2 * c2 * sp.exp(-I * ph) * Yp * up
    Lm = d1 * Y * down + s2 * d2 * sp.exp(-I * ph) * Yp * up
    return {+1: ph_t * spinor(sig_n * Up, I * Lp), -1: ph_t * spinor(sig_n * Um, I * Lm)}

def metric_axial():
    h = sp.zeros(4)
    h[0, 3] = h[3, 0] = F['h0'] * s_ * Yp
    h[1, 3] = h[3, 1] = F['h1'] * s_ * Yp
    return h

def project(o):
    s, c, sp_, cp = o['pt']
    eip = cp + I * sp_; cot = c / s
    sn = sp.Matrix([[c, s * (cp - I * sp_)], [s * (cp + I * sp_), -c]])
    bad = []
    D1 = o['dirac'][+1][1]
    up_ = sn * sp.Matrix(D1[:2]); lo_ = D1[2:]
    A1 = simp(up_[0]); A2 = simp(up_[1] / eip); C1 = simp(lo_[0]); C2 = simp(lo_[1] / eip)
    bad += [sp.diff(A1, y1), sp.diff(C1, y1), sp.diff(A2, y0), sp.diff(C2, y0)]
    co = dict(A1=simp(A1 / y0), A2=simp(A2 / y1), C1=simp(C1 / y0), C2=simp(C2 / y1))
    E = o['Ein1']
    co['Etph'] = simp(E[0, 3] / (s * y1)); bad.append(sp.diff(E[0, 3], y0))
    co['Erph'] = simp(E[1, 3] / (s * y1)); bad.append(sp.diff(E[1, 3], y0))
    ang = -2 * cot * y1 - Lam * y0                          # Y'' - cot Y'
    e = simp(E[2, 3] / s)
    co['Ethph'] = simp(sp.diff(e, y0) / (-Lam))
    bad.append(simp(sp.diff(e, y1) - co['Ethph'] * (-2 * cot)))
    polar = [E[0, 0], E[0, 1], E[1, 1], E[0, 2], E[1, 2], E[2, 2], E[3, 3]]
    return co, bad, polar

FIELDS = AMAT + AMET
DERIVS = ['', '_t', '_r', '_tt', '_tr', '_rr']

def write_coeffs(CO):
    rows = {}
    for k in ('A1', 'A2', 'C1', 'C2'):
        e = sp.expand(CO[k])
        rows[k + 're'] = sp.expand((e + sp.conjugate(e)) / 2)
        rows[k + 'im'] = sp.expand((e - sp.conjugate(e)) / (2 * I))
    for k in ('Etph', 'Erph', 'Ethph'):
        rows[k] = sp.expand(CO[k])
    out = ['"""generated by derivations/dirac_axial.py: projected linearised axial-parity (M = 0) equations of free Dirac',
           '   stars, Regge-Wheeler gauge.  ROWS[name](r, omega, mu, Lam, g, f, X, alpha) -> {(field, deriv): coefficient};',
           '   fields cR1 cI1 cR2 cI2 dR1 dI1 dR2 dI2 h0 h1."""',
           'import numpy as np', 'from numpy import pi, sqrt', '', 'ROWS = {}', '']
    summary = []
    for name, e in rows.items():
        terms = []; rest = e
        for n in FIELDS:
            for d in DERIVS:
                sym = sp.Symbol(n + d, real=True)
                cf = sp.factor(sp.cancel(e.coeff(sym)))
                rest = rest - cf * sym
                if cf != 0:
                    terms.append(((n, d), cf))
        assert sp.simplify(sp.expand(rest)) == 0, (name, rest)
        out.append('def _%s(r, omega, mu, Lam, g_, f_, X_, al_):' % name)
        out.append('    z = np.zeros_like(r)')
        out.append('    return {')
        for (n, d), cf in terms:
            out.append('        (%r, %r): (%s) + z,' % (n, d, sp.pycode(cf).replace('math.', '').replace('Lambda', 'Lam')))
        out.append('    }')
        out.append('ROWS[%r] = _%s' % (name, name))
        out.append('')
        summary.append('%-6s: %s' % (name, ' '.join(n + d for (n, d), _ in terms)))
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'relaxation', 'dirac_axial_coeffs.py')
    open(path, 'w').write('\n'.join(out))
    log('coefficients written to relaxation/dirac_axial_coeffs.py')
    for sl in summary:
        print('   ' + sl)

if __name__ == '__main__':
    s2_list = [int(a) for a in sys.argv[1].split(',')] if len(sys.argv) > 1 else [+1, -1]
    for s2 in s2_list:
        o = linearised(metric_axial(), dpsi_axial(s2), 'axial s2=%+d' % s2)
        cos_, ok_close, ok_polar = [], True, True
        for oo in o:
            co, bad, polar = project(oo)
            cos_.append(co)
            ok_close &= all(simp(b) == 0 for b in bad)
            ok_polar &= all(simp(p) == 0 for p in polar)
        same = all(simp(cos_[0][k] - cos_[1][k]) == 0 for k in cos_[0])
        log('s2 = %+d: closes %s, same at both points %s, polar Einstein components vanish %s' % (s2, ok_close, same, ok_polar))
        if ok_close and same and ok_polar:
            CO = cos_[0]
            # - spinor: symmetry image of the + one
            oo = o[0]; s, c, sp_, cp = oo['pt']; emip = cp - I * sp_
            sn = sp.Matrix([[c, s * (cp - I * sp_)], [s * (cp + I * sp_), -c]])
            D1m = oo['dirac'][-1][1]
            upm = sn * sp.Matrix(D1m[:2]); lom = D1m[2:]
            chk = [simp(upm[1] - CO['A1'] * y0), simp(upm[0] - s2 * CO['A2'] * emip * y1),
                   simp(lom[1] - CO['C1'] * y0), simp(lom[0] - s2 * CO['C2'] * emip * y1)]
            assert all(x == 0 for x in chk), chk
            log('   - spinor is the symmetry image of the + spinor: OK; using s2 = %+d' % s2)
            write_coeffs(CO)
            break
